<?php

declare(strict_types=1);

/**
 * Reads an Amazon India category template (.xlsm/.xlsx from Seller Central > Add products via upload)
 * and writes a PHP schema file with its column layout and dropdown values.
 * The seller-specific settings row (contributor id, template id) is NOT copied.
 *
 * Usage: php bin/import-amazon-template.php <template.xlsm> <output.php>
 */

require dirname(__DIR__) . '/vendor/autoload.php';

use PhpOffice\PhpSpreadsheet\IOFactory;

[$self, $in, $out] = $argv + [null, null, null];
if (!$in || !$out) {
    fwrite(STDERR, "Usage: php {$self} <template.xlsm> <output.php>\n");
    exit(1);
}

$reader = IOFactory::createReaderForFile($in);
$reader->setReadDataOnly(true);
$reader->setLoadSheetsOnly(['Template', 'Valid Values']);
$book = $reader->load($in);

$t = $book->getSheetByName('Template');
$settings = (string) $t->getCell('A1')->getValue();
parse_str(str_replace('settings=', '', $settings), $s);
$labelRow = (int) ($s['labelRow'] ?? 4);
$attrRow = (int) ($s['attributeRow'] ?? 5);
$dataRow = (int) ($s['dataRow'] ?? 7);

$rows = $t->rangeToArray('A1:' . $t->getHighestColumn() . $attrRow, null, false, false, false);
$columns = [];
$group = '';
foreach ($rows[$attrRow - 1] as $i => $key) {
    if ($key === null || $key === '') {
        continue;
    }
    $group = (string) ($rows[$labelRow - 2][$i] ?? '') ?: $group;
    $columns[] = ['group' => $group, 'label' => (string) $rows[$labelRow - 1][$i], 'key' => (string) $key];
}

$valid = [];
$vv = $book->getSheetByName('Valid Values')->toArray(null, false, false, false);
foreach ($vv as $r) {
    $label = trim((string) ($r[1] ?? ''));
    if ($label === '') {
        continue;
    }
    $ptype = '*';
    if (preg_match('/^(.*?)\s*-\s*\[\s*(.*?)\s*\]$/', $label, $m)) {
        $label = $m[1];
        $ptype = $m[2] !== '' ? $m[2] : '*';
    }
    $values = array_values(array_filter(array_map(static fn ($v) => trim((string) $v), array_slice($r, 2)), static fn ($v) => $v !== ''));
    $valid[$label][$ptype] = $values;
}

$schema = [
    'source' => basename($in),
    'label_row' => $labelRow,
    'attribute_row' => $attrRow,
    'data_row' => $dataRow,
    'product_types' => $valid['Product Type']['*'] ?? [],
    'columns' => $columns,
    'valid_values' => $valid,
];
file_put_contents($out, "<?php\n\n// Generated by bin/import-amazon-template.php from {$schema['source']}. Do not edit by hand.\n\nreturn "
    . var_export($schema, true) . ";\n");
printf("%d columns, %d dropdown lists, product types: %s\n", count($columns), count($valid), implode(', ', $schema['product_types']));
